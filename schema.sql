PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS TGFVOL(CODVOL TEXT PRIMARY KEY NOT NULL, DESCRVOL TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS TGFGRU(CODGRUPOPROD INTEGER PRIMARY KEY CHECK(CODGRUPOPROD>0), DESCRGRUPOPROD TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS TSIEMP(CODEMP INTEGER PRIMARY KEY, RAZAOSOCIAL TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS TGFLOC(CODLOCAL INTEGER PRIMARY KEY, DESCRLOCAL TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS TGFPAR(CODPARC INTEGER PRIMARY KEY, NOMEPARC TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS TGFPRO(
 CODPROD INTEGER PRIMARY KEY CHECK(CODPROD BETWEEN 1 AND 9999999999),
 DESCRPROD TEXT NOT NULL CHECK(length(trim(DESCRPROD)) BETWEEN 1 AND 100),
 CODVOL TEXT NOT NULL REFERENCES TGFVOL(CODVOL),
 ESTMIN REAL NOT NULL DEFAULT 0 CHECK(ESTMIN BETWEEN 0 AND 999999999),
 CODGRUPOPROD INTEGER NOT NULL DEFAULT 1 REFERENCES TGFGRU(CODGRUPOPROD));
CREATE TABLE IF NOT EXISTS TGFTOP(
 CODTIPOPER INTEGER NOT NULL CHECK(CODTIPOPER BETWEEN 1 AND 99999), DHALTER TEXT NOT NULL,
 DESCROPER TEXT NOT NULL, TIPMOV TEXT NOT NULL CHECK(TIPMOV IN ('C','V','O','P')),
 ATUALEST TEXT NOT NULL CHECK(ATUALEST IN ('E','B','N')),
 PRIMARY KEY(CODTIPOPER,DHALTER),
 CHECK((TIPMOV='C' AND ATUALEST IN ('E','N')) OR (TIPMOV='V' AND ATUALEST IN ('B','N')) OR (TIPMOV IN ('O','P') AND ATUALEST='N')));
CREATE TABLE IF NOT EXISTS TGFCAB(
 NUNOTA INTEGER PRIMARY KEY AUTOINCREMENT, NUMNOTA INTEGER NOT NULL DEFAULT 0 CHECK(NUMNOTA>=0),
 CODEMP INTEGER NOT NULL DEFAULT 1 REFERENCES TSIEMP(CODEMP),
 CODPARC INTEGER NOT NULL REFERENCES TGFPAR(CODPARC), DTNEG TEXT NOT NULL, DTMOV TEXT NOT NULL,
 CODTIPOPER INTEGER NOT NULL, DHTIPOPER TEXT NOT NULL,
 TIPMOV TEXT NOT NULL CHECK(TIPMOV IN ('C','V','O','P')), STATUSNOTA TEXT NOT NULL DEFAULT 'P' CHECK(STATUSNOTA IN ('P','L')),
 VLRNOTA REAL NOT NULL CHECK(VLRNOTA>=0), OBSERVACAO TEXT NOT NULL DEFAULT '',
 FOREIGN KEY(CODTIPOPER,DHTIPOPER) REFERENCES TGFTOP(CODTIPOPER,DHALTER));
CREATE TABLE IF NOT EXISTS TGFITE(
 NUNOTA INTEGER NOT NULL REFERENCES TGFCAB(NUNOTA) ON DELETE CASCADE,
 SEQUENCIA INTEGER NOT NULL CHECK(SEQUENCIA>0), CODEMP INTEGER NOT NULL DEFAULT 1 REFERENCES TSIEMP(CODEMP),
 CODPROD INTEGER NOT NULL REFERENCES TGFPRO(CODPROD),
 CODLOCALORIG INTEGER NOT NULL DEFAULT 1 REFERENCES TGFLOC(CODLOCAL), CONTROLE TEXT NOT NULL DEFAULT ' ',
 CODVOL TEXT NOT NULL REFERENCES TGFVOL(CODVOL), QTDNEG REAL NOT NULL CHECK(QTDNEG>0 AND QTDNEG<=999999999),
 VLRUNIT REAL NOT NULL CHECK(VLRUNIT>=0 AND VLRUNIT<=999999999), VLRTOT REAL NOT NULL CHECK(VLRTOT>=0),
 PRIMARY KEY(NUNOTA,SEQUENCIA));
CREATE TABLE IF NOT EXISTS TGFEST(
 CODEMP INTEGER NOT NULL REFERENCES TSIEMP(CODEMP), CODLOCAL INTEGER NOT NULL REFERENCES TGFLOC(CODLOCAL),
 CODPROD INTEGER NOT NULL REFERENCES TGFPRO(CODPROD), CONTROLE TEXT NOT NULL DEFAULT ' ',
 TIPO TEXT NOT NULL DEFAULT 'P' CHECK(TIPO='P'), CODPARC INTEGER NOT NULL DEFAULT 0 REFERENCES TGFPAR(CODPARC),
 ESTOQUE REAL NOT NULL DEFAULT 0 CHECK(ESTOQUE>=0), RESERVADO REAL NOT NULL DEFAULT 0 CHECK(RESERVADO=0),
 PRIMARY KEY(CODEMP,CODLOCAL,CODPROD,CONTROLE,TIPO,CODPARC));
CREATE INDEX IF NOT EXISTS IX_ITE_PROD ON TGFITE(CODPROD);
CREATE INDEX IF NOT EXISTS IX_CAB_MOV ON TGFCAB(TIPMOV,DTMOV,STATUSNOTA);
